def normalize_lang(code: str | None) -> str:
    value = (code or "fr").strip().lower()
    return value if value in SUPPORTED else "fr"


def text_dir(lang: str) -> str:
    return "rtl" if lang == "he" else "ltr"


def strings_for(lang: str) -> dict[str, str]:
    return _STRINGS[normalize_lang(lang)]


def ui_ctx(request, **extra) -> dict:
    """Classic i18n context: lang + dir + translated strings."""
    lang = normalize_lang(request.cookies.get("lang"))
    return {
        "request": request,
        "lang": lang,
        "dir": text_dir(lang),
        "t": strings_for(lang),
        **extra,
    }
